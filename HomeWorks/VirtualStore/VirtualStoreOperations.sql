-- =====================================================================
-- 3. Выбор всех заказов определенного пользователя
-- =====================================================================
SELECT o."OrderID", o."OrderDate", o."Status",
       u."UserName", u."Email"
FROM "Orders" o
JOIN "Users" u ON u."UserID" = o."UserID"
WHERE u."UserID" = 'b0000000-0000-4000-8000-000000000001';
-- Или по email / имени:
-- WHERE u."Email" = 'ivanov@example.com';

-- =====================================================================
-- 4. Расчет общей стоимости заказа
-- =====================================================================
SELECT od."OrderID",
       SUM(od."TotalCost") AS "TotalOrderCost"
FROM "OrderDetails" od
WHERE od."OrderID" = 'c0000000-0000-4000-8000-000000000001'
GROUP BY od."OrderID";

-- =====================================================================
-- 5. Подсчет количества товаров на складе (всего и по продуктам)
-- =====================================================================
-- Общее количество всех товаров на складе:
SELECT SUM("QuantityInStock") AS "TotalItemsInStock"
FROM "Products";
-- Количество по каждому продукту:
-- SELECT "ProductName", "QuantityInStock" FROM "Products" ORDER BY "QuantityInStock" DESC;

-- =====================================================================
-- 6. Получение 5 самых дорогих товаров
-- =====================================================================
SELECT "ProductName", "Price", "QuantityInStock"
FROM "Products"
ORDER BY "Price" DESC
LIMIT 5;

-- =====================================================================
-- 7. Список товаров с низким запасом (менее 5 штук)
-- =====================================================================
SELECT "ProductName", "QuantityInStock", "Price"
FROM "Products"
WHERE "QuantityInStock" < 5
ORDER BY "QuantityInStock";